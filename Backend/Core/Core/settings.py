def env_flag(name: str, default: bool | None = False) -> bool:
    """Read a boolean without silently treating a typo as ``False``."""

    raw_value = os.environ.get(name)
    if raw_value is None:
        if default is None:
            raise RuntimeError(f'{name} must be explicitly set to true or false.')
        return default
    normalized = raw_value.strip().lower()
    if normalized in {'1', 'true', 'yes', 'on'}:
        return True
    if normalized in {'0', 'false', 'no', 'off'}:
        return False
    raise RuntimeError(f'{name} must be true or false.')


def env_positive_int(name: str, default: int) -> int:
    try:
        value = int(os.environ.get(name, default))
    except ValueError as exc:
        raise RuntimeError(f'{name} must be a positive integer.') from exc
    if value <= 0:
        raise RuntimeError(f'{name} must be a positive integer.')
    return value


def env_nonnegative_int(name: str, default: int) -> int:
    try:
        value = int(os.environ.get(name, default))
    except ValueError as exc:
        raise RuntimeError(f'{name} must be a non-negative integer.') from exc
    if value < 0:
        raise RuntimeError(f'{name} must be a non-negative integer.')
    return value


def env_int_range(name: str, default: int, minimum: int, maximum: int) -> int:
    value = env_positive_int(name, default)
    if not minimum <= value <= maximum:
        raise RuntimeError(f'{name} must be between {minimum} and {maximum}.')
    return value


