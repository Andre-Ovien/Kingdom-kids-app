import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { createPageNotifications } from '../src/scripts/page-notifications.mjs';
import { domFixture } from './dom-fixture.mjs';

test('website deploy copies exactly match the shared merchant notification source', {
  // A website-only deployment/checkout uses committed local copies. The pair
  // check runs when both projects are included, without a deploy dependency.
  skip: !existsSync(new URL('../../../Backend/Core/apps/billing/static/billing/page_notifications.js', import.meta.url)),
}, () => {
  for (const [extension, local, prefix] of [
    ['js', '../src/scripts/page-notifications.mjs', '// Generated by scripts/sync-page-notifications.mjs; edit the shared Backend source.\n'],
    ['css', '../src/styles/page-notifications.css', '/* Generated by scripts/sync-page-notifications.mjs; edit the shared Backend source. */\n'],
  ]) {
    assert.equal(readFileSync(new URL(local, import.meta.url), 'utf8'), prefix +
      readFileSync(new URL(`../../../Backend/Core/apps/billing/static/billing/page_notifications.${extension}`, import.meta.url), 'utf8'));
  }
});

test('real shared toast runs for five seconds then fades; persistent accessible status remains', () => {
  const { doc, options, advance } = domFixture(), source = doc.createElement('p');
  source.textContent = 'Payment is still being checked.';
  const notices = createPageNotifications(doc, options);
  notices.show(source.textContent, { source, tone: 'info' });
  const toast = doc.body.children[0], [icon, message, close, progress] = toast.children;
  assert.equal(toast.getAttribute('aria-live'), 'off');
  assert.equal(icon.getAttribute('aria-hidden'), 'true'); assert.equal(progress.getAttribute('aria-hidden'), 'true');
  assert.equal(close.getAttribute('aria-label'), 'Dismiss notification');
  assert.equal(message.textContent, source.textContent); assert.match(progress.style.animation, /5000ms/);
  advance(4999); assert.equal(toast.hidden, false); assert.equal(toast.classList.contains('is-leaving'), false);
  advance(1); assert.equal(toast.hidden, false); assert.equal(toast.classList.contains('is-leaving'), true);
  advance(180); assert.equal(toast.hidden, true); assert.equal(source.textContent, 'Payment is still being checked.');
});

test('hover, focus and hidden document pause both countdown and visual bar', () => {
  const { doc, options, advance } = domFixture(), notices = createPageNotifications(doc, options);
  notices.show('Your request was sent.', { tone: 'success' });
  const toast = doc.body.children[0], progress = toast.children[3];
  advance(2000); toast.emit('mouseenter'); toast.emit('focusin');
  advance(10000); assert.equal(toast.hidden, false); assert.equal(progress.style.animationPlayState, 'paused');
  toast.emit('mouseleave'); advance(10000); assert.equal(toast.hidden, false);
  toast.emit('focusout', { relatedTarget: null }); doc.hidden = true; doc.emit('visibilitychange');
  advance(10000); assert.equal(toast.hidden, false);
  doc.hidden = false; doc.emit('visibilitychange'); assert.equal(progress.style.animationPlayState, 'running');
  advance(2999); assert.equal(toast.classList.contains('is-leaving'), false);
  advance(181); assert.equal(toast.hidden, true);
});

test('replacing a fading notice cannot hide the new one; dismissal restores focus and never renders HTML', () => {
  const { doc, options, advance } = domFixture(), notices = createPageNotifications(doc, options);
  const source = doc.createElement('p'); notices.show('First'); advance(5000);
  notices.show('<img src=x onerror=alert(1)>', { source, tone: 'error' });
  const toast = doc.body.children[0];
  assert.equal(toast.children[1].textContent, '<img src=x onerror=alert(1)>');
  assert.equal(toast.children[1].children.length, 0);
  advance(180); assert.equal(toast.hidden, false); assert.equal(toast.classList.contains('is-leaving'), false);
  toast.children[2].focus(); toast.children[2].emit('click'); assert.equal(toast.hidden, true); assert.equal(doc.activeElement, source);
  notices.dispose(); assert.equal(doc.body.children.length, 0);
});

test('countdown right edge retreats left, with reduced-motion and fade alternatives', () => {
  const css = readFileSync(new URL('../src/styles/page-notifications.css', import.meta.url), 'utf8');
  assert.match(css, /transform-origin:\s*left center/);
  assert.match(css, /form-toast-countdown[^}]*scaleX\(1\)[\s\S]*scaleX\(0\)/);
  assert.match(css, /is-leaving[^}]*opacity:\s*0/); assert.match(css, /prefers-reduced-motion:\s*reduce/);
});
