// Optional repository development command; deploy builds use committed copies
// and need no access outside the website project root.
import { readFile, writeFile } from 'node:fs/promises';

const check = process.argv.includes('--check');
for (const [extension, destination, prefix] of [
  ['js', '../src/scripts/page-notifications.mjs', '// Generated by scripts/sync-page-notifications.mjs; edit the shared Backend source.\n'],
  ['css', '../src/styles/page-notifications.css', '/* Generated by scripts/sync-page-notifications.mjs; edit the shared Backend source. */\n'],
]) {
  const source = new URL(`../../../Backend/Core/apps/billing/static/billing/page_notifications.${extension}`, import.meta.url);
  const target = new URL(destination, import.meta.url);
  const expected = prefix + await readFile(source, 'utf8');
  if (check) {
    if (await readFile(target, 'utf8') !== expected) throw new Error('Shared notification copies differ; run scripts/sync-page-notifications.mjs locally.');
  } else await writeFile(target, expected);
}
console.log(check ? 'Shared notification copies match.' : 'Shared notification copies refreshed.');
